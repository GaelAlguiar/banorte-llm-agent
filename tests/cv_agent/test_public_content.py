from pathlib import Path
import re
import subprocess


def _tracked_files() -> tuple[Path, ...]:
    result = subprocess.run(
        ["git", "ls-files", "-z"],
        check=True,
        capture_output=True,
    )
    return tuple(Path(item.decode()) for item in result.stdout.split(b"\0") if item)


def test_repository_has_no_irrelevant_dotnet_language_example():
    forbidden = "c" + "#"
    roots = (
        Path("cv_agent"),
        Path("evals"),
        Path("knowledge"),
        Path("tests"),
        Path("README.md"),
    )
    matches = []
    for root in roots:
        paths = [root] if root.is_file() else root.rglob("*")
        for path in paths:
            if path.is_file() and path.suffix in {".py", ".md", ".yaml", ".jsonl"}:
                if forbidden in path.read_text(encoding="utf-8").casefold():
                    matches.append(str(path))

    assert matches == []


